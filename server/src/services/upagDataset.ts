function createMonthMap(specs: {
  sowing: { months: number[]; timing?: Record<number, string> };
  growing: { months: number[] };
  harvesting: { months: number[]; timing?: Record<number, string> };
}): Record<number, MonthPhaseDetail> {
  const map: Record<number, MonthPhaseDetail> = {};

  for (let m = 1; m <= 12; m++) {
    const monthName = MONTH_NAMES[m - 1];
    let phase: CropPhase = 'off';
    let timing: string | undefined;
    let timingCode: string | undefined;

    if (specs.sowing.months.includes(m)) {
      phase = 'sowing';
      timing = specs.sowing.timing?.[m] || 'Normal';
    } else if (specs.harvesting.months.includes(m)) {
      phase = 'harvesting';
      timing = specs.harvesting.timing?.[m] || 'Normal';
    } else if (specs.growing.months.includes(m)) {
      phase = 'growing';
    }

    if (timing) {
      if (timing.toLowerCase().includes('early')) timingCode = 'E';
      else if (timing.toLowerCase().includes('middle')) timingCode = 'M';
      else if (timing.toLowerCase().includes('late')) timingCode = 'L';
      else if (timing.toLowerCase().includes('beginning')) timingCode = 'B';
    }

    map[m] = {
      month: m,
      monthName,
      phase,
      timing,
      timingCode,
    };
  }

  return map;
}

