export type CropPhase = 'sowing' | 'growing' | 'harvesting' | 'off';

export interface MonthPhaseDetail {
  month: number; // 1 = Jan, 12 = Dec
  monthName: string;
  phase: CropPhase;
  timing?: string; // 'Early' | 'Middle' | 'Late' | 'Beginning' | 'Beginning to Middle' | 'Middle to End'
  timingCode?: string; // 'E' | 'M' | 'L' | 'B' | 'B-M' | 'M-E'
}

export interface UPAgCropRecord {
  id: string;
  state: string;
  season: 'Kharif' | 'Rabi' | 'Zaid / Summer' | 'Annual';
  crop: string;
  localName: string; // Hindi / local script name
  primaryCategory: 'Foodgrain' | 'Oilseeds' | 'Pulses' | 'Commercial' | 'Horticulture' | 'Fibre';
  sowingWindow: string;
  growingWindow: string;
  harvestingWindow: string;
  months: Record<number, MonthPhaseDetail>;
  source: string;
}

